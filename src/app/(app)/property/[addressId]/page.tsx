import type { Metadata } from "next";
import Link from "next/link";
import { notFound, redirect } from "next/navigation";
import { ScorePanel } from "@/components/property/ScorePanel";
import { PermitAbsencePanel } from "@/components/property/PermitAbsencePanel";
import { TcoTable } from "@/components/property/TcoTable";
import { OpportunityCard, ZoningHeadroomPanel } from "@/components/property/OpportunityPanel";
import { ConfidenceLegend, SourcedFact } from "@/components/property/Provenance";
import { UnknownChip } from "@/components/viz/primitives";
import { StatGrid, StatTile } from "@/components/viz/StatTile";
import { createClient } from "@/lib/supabase/server";
import { formatCents } from "@/lib/money";
import { INVESTOR_GF_V1, scoreSubject } from "@/lib/scoring/engine";
import {
  assessAduFeasibility,
  assessLotSplit,
  assessOccupancyCap,
  assessZoningHeadroom,
} from "@/lib/intel/opportunity";
import { assessAllPermitSignals, summarizeCoverage } from "@/lib/intel/permits";
import { computeTco, type TaxInputs } from "@/lib/intel/tco";
import { getDossier, provenanceFor, toScoringSubject } from "../_data";

export const metadata: Metadata = {
  title: "Property — Realestate Genius",
  robots: { index: false, follow: false },
};

export const dynamic = "force-dynamic";

/**
 * Analysis by address.
 *
 * Every number on this page is computed by deterministic TypeScript from
 * sourced inputs, and every displayed fact carries its source, its observation
 * date and its confidence. Nothing here is generated by a model.
 *
 * Sections degrade independently: no zoning row means no opportunity analysis
 * and a stated reason, not a blank page. That matters because the intelligence
 * layer is populated per jurisdiction — a property in a county we have not
 * ingested is a normal state.
 */
export default async function PropertyPage({
  params,
}: {
  params: Promise<{ addressId: string }>;
}) {
  const { addressId } = await params;

  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) redirect(`/sign-in?next=/property/${addressId}`);

  const { data: dossier, schemaReady, error } = await getDossier(addressId);

  if (!schemaReady) {
    return (
      <main className="mx-auto w-full max-w-3xl px-6 py-16">
        <div className="rounded-2xl border border-caution/45 bg-caution-soft p-6">
          <h1 className="text-title-lg text-fg">The property schema is not deployed</h1>
          <p className="mt-2 text-body text-fg-muted">
            Apply the base migration before loading a property.
          </p>
          {error ? (
            <p className="mt-3 font-mono text-micro uppercase text-fg-subtle">{error}</p>
          ) : null}
        </div>
      </main>
    );
  }
  if (!dossier) notFound();

  const { address, parcel, zoning, permits, hazards, assessments, listing, sources } = dossier;

  // ---- Deterministic score -------------------------------------------------
  const subject = toScoringSubject(dossier);
  const analysis = scoreSubject(subject, INVESTOR_GF_V1, {
    // No area median is loaded here: the market-stats materialized view is a
    // separate build. The factor takes the neutral-half-credit path and says so,
    // which is the correct behaviour and visible in the panel's gap list.
    area_median_price_per_sqft_cents: null,
    area_median_geography: "postal_code",
  });

  // ---- Cost of ownership ---------------------------------------------------
  const latestAssessment = assessments[0] ?? null;
  const tax: TaxInputs = latestAssessment?.tax_billed_cents
    ? {
        kind: "billed",
        annual_billed_cents: latestAssessment.tax_billed_cents,
        tax_year: latestAssessment.tax_year,
        source: sources[latestAssessment.source_id]?.display_name ?? "county assessor",
      }
    : latestAssessment?.assessed_total_cents && latestAssessment.mill_rate
      ? {
          kind: "mill_rate",
          assessed_total_cents: latestAssessment.assessed_total_cents,
          mill_rate: latestAssessment.mill_rate,
          tax_year: latestAssessment.tax_year,
          source: sources[latestAssessment.source_id]?.display_name ?? "county assessor",
        }
      : { kind: "unknown" };

  const inSfha = hazards.some(
    (h) =>
      h.hazard_type === "fema_flood_zone" &&
      h.classification !== null &&
      /^(A|V)/i.test(h.classification),
  );
  const radonFlagged = hazards.some((h) => h.hazard_type === "radon_zone" && h.is_high_risk === true);

  const tco =
    listing?.price_cents != null
      ? computeTco({
          purchase_price_cents: listing.price_cents,
          // No loan terms are assumed. A default rate would be a fabricated
          // input on the largest line in the table.
          loan: null,
          tax,
          in_sfha: inSfha,
          radon_flagged: radonFlagged,
          sqft_above_grade: listing.sqft_above_grade,
        })
      : null;

  // ---- Opportunity ---------------------------------------------------------
  const unitCount = parcel && listing?.property_type === "Duplex" ? 2 : 1;
  const opportunity = zoning
    ? {
        headroom: assessZoningHeadroom({
          zoning,
          lot_size_sqft: parcel?.lot_size_sqft ?? listing?.lot_size_sqft ?? null,
          current_units: unitCount,
          current_height_ft: null,
          current_footprint_sqft: null,
          current_floor_area_sqft: listing?.sqft_total ?? null,
          max_far: null,
        }),
        adu: assessAduFeasibility({
          zoning,
          lot_size_sqft: parcel?.lot_size_sqft ?? listing?.lot_size_sqft ?? null,
          existing_footprint_sqft: null,
          existing_units: unitCount,
        }),
        split: assessLotSplit({
          zoning,
          lot_size_sqft: parcel?.lot_size_sqft ?? listing?.lot_size_sqft ?? null,
        }),
        occupancy: assessOccupancyCap({
          zoning,
          unit_count: unitCount,
          bedrooms_per_unit: listing?.beds != null ? [listing.beds] : [],
        }),
      }
    : null;

  // ---- Permits -------------------------------------------------------------
  // No coverage row is loaded (permit coverage is recorded per jurisdiction as
  // part of the ingestion work). Passing null is correct and produces the
  // "we cannot claim absence" path rather than a false finding.
  const permitSignals = assessAllPermitSignals([], permits, [], null);

  return (
    <main className="mx-auto w-full max-w-5xl px-6 py-12 md:px-10 md:py-16">
      <Link
        href="/search"
        className="font-mono text-micro uppercase text-fg-subtle transition-colors hover:text-fg"
      >
        ← Search
      </Link>

      <header className="mt-6">
        <p className="font-mono text-micro uppercase text-fg-subtle">Analysis by address</p>
        <h1 className="mt-2 font-display text-display-xs text-fg">
          {address.line1}
          {address.line2 ? ` ${address.line2}` : ""}
        </h1>
        <p className="mt-1 text-body-lg text-fg-muted">
          {address.city}, {address.state} {address.postal_code}
        </p>
      </header>

      <StatGrid className="mt-8">
        <StatTile
          label="Asking"
          value={listing?.price_cents != null ? formatCents(listing.price_cents) : null}
          unknownReason="no active listing"
          emphasis
          source={listing ? listing.source_slugs.join(", ") || "listing feed" : undefined}
          asOf={listing?.last_seen_at.slice(0, 10)}
        />
        <StatTile
          label="Assessed"
          value={
            latestAssessment?.assessed_total_cents != null
              ? formatCents(latestAssessment.assessed_total_cents)
              : null
          }
          unknownReason="no assessment on record"
          hint={
            latestAssessment?.assessment_ratio == null
              ? "No assessment ratio published — implied market value is not computed rather than assumed."
              : `Assessed at ${(latestAssessment.assessment_ratio * 100).toFixed(1)}% of market.`
          }
          source={
            latestAssessment ? sources[latestAssessment.source_id]?.display_name : undefined
          }
          asOf={latestAssessment?.observed_at.slice(0, 10)}
        />
        <StatTile
          label="Lot"
          value={
            parcel?.lot_size_sqft != null
              ? parcel.lot_size_sqft.toLocaleString("en-US")
              : listing?.lot_size_sqft != null
                ? listing.lot_size_sqft.toLocaleString("en-US")
                : null
          }
          unit="sqft"
          unknownReason="no parcel record"
          source={parcel ? sources[parcel.source_id]?.display_name : undefined}
          asOf={parcel?.observed_at.slice(0, 10)}
        />
        <StatTile
          label="Zoning"
          value={zoning?.code ?? null}
          unknownReason="district not resolved"
          hint={
            zoning
              ? zoning.verified_at
                ? `Verified ${zoning.verified_at.slice(0, 10)}`
                : "Unverified — confirm with the city before acting on any figure derived from it."
              : undefined
          }
          caution={zoning && !zoning.verified_at ? "Unverified rule set" : undefined}
          source={zoning?.ordinance_citation}
        />
      </StatGrid>

      <div className="mt-10 space-y-8">
        <ScorePanel analysis={analysis} />

        {tco ? (
          <TcoTable tco={tco} />
        ) : (
          <section className="rounded-2xl border border-dashed border-line-strong bg-surface-2/60 p-6">
            <h2 className="text-title-lg text-fg">Cost of ownership</h2>
            <p className="mt-2 max-w-prose text-body text-fg-muted">
              No purchase price on record, so there is nothing to cost. The table needs a price plus
              either a county-billed tax amount or a mill rate — it will not model a tax figure from
              an assessed value without knowing the taxable base.
            </p>
            <div className="mt-3">
              <UnknownChip reason="no listing price">Not computed</UnknownChip>
            </div>
          </section>
        )}

        <PermitAbsencePanel
          findings={permitSignals.findings}
          permits={permits}
          summary={
            permits.length === 0
              ? "No permit records held for this address. That is a statement about our coverage, not about the property."
              : permitSignals.summary
          }
          coverageStatement={summarizeCoverage(null)}
        />

        {opportunity ? (
          <>
            <ZoningHeadroomPanel result={opportunity.headroom} zoneCode={zoning?.code ?? null} />
            <OpportunityCard title="ADU feasibility" result={opportunity.adu} />
            <OpportunityCard title="Lot split" result={opportunity.split} />
            <OpportunityCard title="Occupancy and room-rental capacity" result={opportunity.occupancy} />
          </>
        ) : (
          <section className="rounded-2xl border border-dashed border-line-strong bg-surface-2/60 p-6">
            <h2 className="text-title-lg text-fg">Opportunity analysis</h2>
            <p className="mt-2 max-w-prose text-body text-fg-muted">
              No zoning district is resolved for this parcel, so ADU feasibility, lot-split
              arithmetic, headroom and occupancy capacity cannot be computed. Zoning is modelled per
              city and requires reading the ordinance — it is not inferred from the parcel record.
            </p>
          </section>
        )}

        <section className="rounded-2xl border border-dashed border-line-strong bg-surface-2/60 p-6">
          <h2 className="text-title-lg text-fg">Comparable sales</h2>
          <p className="mt-2 max-w-prose text-body text-fg-muted">
            Not computed here. Comparable selection weights on straight-line distance, and that
            needs a geospatial query against <code className="font-mono">addresses.geom</code>{" "}
            (a PostGIS RPC) rather than a postal-code filter. Substituting a placeholder distance
            would silently corrupt the weighting, so the section stays empty until the query exists.
          </p>
          <p className="mt-3 max-w-prose text-body-sm text-fg-subtle">
            The engine itself is built and reachable: POST a subject and a comp pool to{" "}
            <code className="font-mono">/api/property/analyze</code> and it returns a weighted range
            with a confidence band, the comps it used, and the ones it excluded with reasons. It
            never returns a single valuation number.
          </p>
          <div className="mt-3">
            <UnknownChip reason="needs a geospatial comp query">Not computed</UnknownChip>
          </div>
        </section>

        <section className="rounded-2xl border border-line bg-surface-2/80 p-5 md:p-6">
          <h2 className="font-display text-title-lg text-fg">Everything on record</h2>
          <p className="mt-1 max-w-prose text-body-sm text-fg-muted">
            Each value shows where it came from and when it was observed. A number without that is
            worse than no number.
          </p>

          <div className="mt-5">
            {hazards.map((h) => (
              <SourcedFact
                key={h.id}
                label={h.hazard_type.replace(/_/g, " ")}
                value={h.classification ?? "not mapped"}
                provenance={provenanceFor(sources, h.source_id, h.observed_at)}
                hint={
                  h.sub_type
                    ? `Sub-type: ${h.sub_type}. Read this alongside the zone — a levee-protected Zone X is not an absence of flood risk.`
                    : h.classification === null
                      ? "No feature returned means the address is not in a detailed flood study. It does not mean there is no flood risk."
                      : undefined
                }
              />
            ))}
            {assessments.map((a) => (
              <SourcedFact
                key={a.id}
                label={`Assessed value ${a.tax_year}`}
                value={
                  a.assessed_total_cents != null ? formatCents(a.assessed_total_cents) : "—"
                }
                provenance={provenanceFor(sources, a.source_id, a.observed_at)}
                hint={
                  a.assessment_ratio == null
                    ? "The county did not publish an assessment ratio for this year, so implied market value is left uncomputed."
                    : undefined
                }
              />
            ))}
            {dossier.facts.slice(0, 40).map((f) => (
              <SourcedFact
                key={f.fact_key}
                label={f.fact_key.replace(/_/g, " ")}
                value={
                  f.value_money_cents != null
                    ? formatCents(f.value_money_cents)
                    : String(
                        f.value_int ??
                          f.value_number ??
                          f.value_text ??
                          f.value_bool ??
                          f.value_date ??
                          "—",
                      )
                }
                provenance={provenanceFor(sources, f.source_id, f.observed_at, f.confidence)}
              />
            ))}
            {hazards.length === 0 && assessments.length === 0 && dossier.facts.length === 0 ? (
              <p className="text-body-sm text-fg-subtle">
                No facts ingested for this address yet.
              </p>
            ) : null}
          </div>

          <div className="mt-6 border-t border-line pt-4">
            <p className="mb-3 font-mono text-micro uppercase text-fg-subtle">
              What the confidence labels mean
            </p>
            <ConfidenceLegend />
          </div>
        </section>
      </div>
    </main>
  );
}
